import { createVerify } from "node:crypto";
import { AwsClient } from "aws4fetch";
import { z } from "zod";

import type { BounceEvent, IntegrationProvider } from "./types.js";
import { InvalidWebhookError } from "../../inbound/inboundSource.js";
import { webhookUrl, withWebhookToken } from "../../inbound/webhookToken.js";

const configSchema = z.object({
  region: z
    .string()
    .regex(/^[a-z]{2}(-[a-z]+)+-\d$/)
    .describe("AWS region the SES identity is in, e.g. us-east-1."),
  fromEmail: z.string().email(),
  fromName: z.string().max(255).optional(),
  replyTo: z
    .string()
    .email()
    .optional()
    .describe(
      "Where replies go, if not fromEmail - e.g. when the sending subdomain has no inbox.",
    ),
  configurationSetName: z
    .string()
    .min(1)
    .optional()
    .describe("SES configuration set to send with."),
  webhookToken: z
    .string()
    .optional()
    .describe("Generated by subscriber.dev; any value sent is ignored."),
});

const secretSchema = z.object({
  accessKeyId: z.string().min(1),
  secretAccessKey: z.string().min(1),
});

type SesConfig = z.infer<typeof configSchema>;
type SesSecret = z.infer<typeof secretSchema>;

const SNS_HOST = /^sns\.[a-z0-9-]+\.amazonaws\.com(\.cn)?$/;

const NOTIFICATION_FIELDS = [
  "Message",
  "MessageId",
  "Subject",
  "Timestamp",
  "TopicArn",
  "Type",
];
const CONFIRMATION_FIELDS = [
  "Message",
  "MessageId",
  "SubscribeURL",
  "Timestamp",
  "Token",
  "TopicArn",
  "Type",
];

type SnsMessage = Record<string, string | undefined>;

const certificates = new Map<string, Promise<string>>();

function snsUrl(value: string | undefined): URL {
  let url: URL;
  try {
    url = new URL(value ?? "");
  } catch {
    throw new InvalidWebhookError("Invalid SNS URL");
  }
  if (url.protocol !== "https:" || !SNS_HOST.test(url.hostname)) {
    throw new InvalidWebhookError("SNS URL isn't on an AWS SNS host");
  }
  return url;
}

function certificate(certUrl: string | undefined): Promise<string> {
  const url = snsUrl(certUrl);
  if (!url.pathname.endsWith(".pem")) {
    throw new InvalidWebhookError("SNS certificate URL isn't a .pem file");
  }
  const key = url.toString();
  let pending = certificates.get(key);
  if (!pending) {
    pending = fetch(url, { signal: AbortSignal.timeout(10_000) }).then(
      async (response) => {
        if (!response.ok) throw new Error("Couldn't fetch SNS certificate");
        return response.text();
      },
    );
    pending.catch(() => certificates.delete(key));
    certificates.set(key, pending);
  }
  return pending;
}

export function snsStringToSign(message: SnsMessage): string {
  const fields =
    message.Type === "Notification" ? NOTIFICATION_FIELDS : CONFIRMATION_FIELDS;
  return fields
    .filter((field) => message[field] !== undefined)
    .map((field) => `${field}\n${message[field]}\n`)
    .join("");
}

export async function verifySnsMessage(
  message: SnsMessage,
  fetchCertificate: (url: string | undefined) => Promise<string> = certificate,
): Promise<void> {
  const algorithm =
    message.SignatureVersion === "1"
      ? "RSA-SHA1"
      : message.SignatureVersion === "2"
        ? "RSA-SHA256"
        : null;
  if (!algorithm || !message.Signature) {
    throw new InvalidWebhookError("Unsupported SNS signature");
  }
  const pem = await fetchCertificate(message.SigningCertURL);
  const valid = createVerify(algorithm)
    .update(snsStringToSign(message), "utf8")
    .verify(pem, message.Signature, "base64");
  if (!valid) throw new InvalidWebhookError("Invalid SNS signature");
}

interface SesNotification {
  notificationType?: string;
  eventType?: string;
  mail?: { messageId?: string; timestamp?: string };
  bounce?: {
    bounceType?: string;
    bounceSubType?: string;
    timestamp?: string;
    bouncedRecipients?: { diagnosticCode?: string }[];
  };
  complaint?: { timestamp?: string; complaintFeedbackType?: string };
}

export function sesBounceEvents(notification: SesNotification): BounceEvent[] {
  const messageId = notification.mail?.messageId;
  if (!messageId) return [];
  const type = notification.notificationType ?? notification.eventType;
  if (type === "Complaint") {
    if (notification.complaint?.complaintFeedbackType === "not-spam") return [];
    return [
      {
        providerMessageId: messageId,
        bounceType: "hard",
        reason: "Marked as spam",
        occurredAt: new Date(notification.complaint?.timestamp ?? Date.now()),
      },
    ];
  }
  if (type !== "Bounce") return [];
  const bounce = notification.bounce;
  return [
    {
      providerMessageId: messageId,
      bounceType: bounce?.bounceType === "Permanent" ? "hard" : "soft",
      reason:
        bounce?.bouncedRecipients?.[0]?.diagnosticCode ??
        [bounce?.bounceType, bounce?.bounceSubType].filter(Boolean).join(": "),
      occurredAt: new Date(bounce?.timestamp ?? Date.now()),
    },
  ];
}

function client(config: SesConfig, secret: SesSecret) {
  const aws = new AwsClient({
    accessKeyId: secret.accessKeyId,
    secretAccessKey: secret.secretAccessKey,
    service: "ses",
    region: config.region,
  });
  const base = `https://email.${config.region}.amazonaws.com/v2/email`;
  return (path: string, init?: RequestInit) =>
    aws.fetch(`${base}${path}`, init);
}

async function sesError(response: Response): Promise<string> {
  const body = (await response.json().catch(() => null)) as {
    message?: string;
    Message?: string;
  } | null;
  return body?.message ?? body?.Message ?? `HTTP ${response.status}`;
}

export const sesProvider: IntegrationProvider<SesConfig, SesSecret> = {
  type: "ses",
  configSchema,
  secretSchema,
  verify: async (config, secret) => {
    const ses = client(config, secret);
    const account = await ses("/account");
    if (!account.ok) {
      throw new Error(
        `AWS keys didn't work for SES: ${await sesError(account)}`,
      );
    }
    const { SendingEnabled } = (await account.json()) as {
      SendingEnabled?: boolean;
    };
    if (SendingEnabled === false) {
      throw new Error(
        `Sending is paused on this SES account in ${config.region}`,
      );
    }
    const domain = config.fromEmail.split("@")[1] ?? "";
    for (const identity of [config.fromEmail, domain]) {
      const response = await ses(`/identities/${encodeURIComponent(identity)}`);
      if (!response.ok) continue;
      const { VerifiedForSendingStatus } = (await response.json()) as {
        VerifiedForSendingStatus?: boolean;
      };
      if (VerifiedForSendingStatus) return;
    }
    throw new Error(
      `Verify ${config.fromEmail} or ${domain} in SES (${config.region}) first`,
    );
  },
  prepareConfig: withWebhookToken,
  describe: (config) => ({
    webhookUrl: webhookUrl("ses", config.webhookToken),
    eventsToEnable: ["Bounce", "Complaint"],
  }),
  send: async (config, secret, message) => {
    const fromName = message.fromName ?? config.fromName;
    const replyTo = message.replyTo ?? config.replyTo;
    const response = await client(config, secret)("/outbound-emails", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        FromEmailAddress: fromName
          ? `${fromName} <${config.fromEmail}>`
          : config.fromEmail,
        Destination: { ToAddresses: [message.to] },
        ...(replyTo ? { ReplyToAddresses: [replyTo] } : {}),
        ...(config.configurationSetName
          ? { ConfigurationSetName: config.configurationSetName }
          : {}),
        Content: {
          Simple: {
            Subject: { Data: message.subject, Charset: "UTF-8" },
            Body: {
              Html: { Data: message.html, Charset: "UTF-8" },
              Text: { Data: message.text, Charset: "UTF-8" },
            },
            ...(message.headers
              ? {
                  Headers: Object.entries(message.headers).map(
                    ([Name, Value]) => ({ Name, Value }),
                  ),
                }
              : {}),
          },
        },
      }),
    });
    if (!response.ok) {
      throw new Error(`SES send failed: ${await sesError(response)}`);
    }
    const { MessageId } = (await response.json()) as { MessageId: string };
    return { providerMessageId: MessageId };
  },
  parseWebhook: async ({ rawBody }) => {
    let message: SnsMessage;
    try {
      message = JSON.parse(rawBody.toString("utf8")) as SnsMessage;
    } catch {
      throw new InvalidWebhookError("Webhook body isn't JSON");
    }
    await verifySnsMessage(message);
    if (message.Type === "SubscriptionConfirmation") {
      const confirm = await fetch(snsUrl(message.SubscribeURL), {
        signal: AbortSignal.timeout(10_000),
      });
      if (!confirm.ok) throw new Error("Couldn't confirm the SNS subscription");
      return [];
    }
    if (message.Type !== "Notification" || !message.Message) return [];
    try {
      return sesBounceEvents(JSON.parse(message.Message) as SesNotification);
    } catch {
      return [];
    }
  },
};
