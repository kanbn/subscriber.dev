import { createHmac, timingSafeEqual } from "node:crypto";
import { z } from "zod";

import type { BounceEvent, IntegrationProvider } from "./types.js";
import { InvalidWebhookError } from "../../inbound/inboundSource.js";
import { webhookUrl, withWebhookToken } from "../../inbound/webhookToken.js";

const API = "https://api.resend.com";
const WEBHOOK_TOLERANCE_SECONDS = 5 * 60;

const configSchema = z.object({
  fromEmail: z.string().email(),
  fromName: z.string().max(255).optional(),
  replyTo: z
    .string()
    .email()
    .optional()
    .describe(
      "Where replies go, if not fromEmail - e.g. when the sending subdomain has no inbox.",
    ),
  webhookToken: z
    .string()
    .optional()
    .describe("Generated by subscriber.dev; any value sent is ignored."),
});

const secretSchema = z.object({
  apiKey: z.string().startsWith("re_").describe("A Resend API key."),
  webhookSecret: z
    .string()
    .startsWith("whsec_")
    .optional()
    .describe(
      "Signing secret of the Resend webhook, so bounces and spam complaints opt people out. Add it once the webhook is created in Resend.",
    ),
});

type ResendConfig = z.infer<typeof configSchema>;
type ResendSecret = z.infer<typeof secretSchema>;

interface ResendError {
  name?: string;
  message?: string;
}

async function resendError(response: Response): Promise<ResendError> {
  return ((await response.json().catch(() => null)) ?? {}) as ResendError;
}

function header(
  headers: Record<string, string | string[] | undefined>,
  name: string,
): string {
  const value = headers[name];
  return (Array.isArray(value) ? value[0] : value) ?? "";
}

export function verifyResendSignature(input: {
  rawBody: Buffer;
  headers: Record<string, string | string[] | undefined>;
  secret: string;
  now?: Date;
}): void {
  const id = header(input.headers, "svix-id");
  const timestamp = header(input.headers, "svix-timestamp");
  const signatures = header(input.headers, "svix-signature");
  if (!id || !timestamp || !signatures) {
    throw new InvalidWebhookError("Missing webhook signature headers");
  }
  const seconds = Number(timestamp);
  const nowSeconds = (input.now ?? new Date()).getTime() / 1000;
  if (
    !Number.isFinite(seconds) ||
    Math.abs(nowSeconds - seconds) > WEBHOOK_TOLERANCE_SECONDS
  ) {
    throw new InvalidWebhookError("Webhook timestamp is too old or too new");
  }
  const key = Buffer.from(input.secret.replace(/^whsec_/, ""), "base64");
  const expected = createHmac("sha256", key)
    .update(`${id}.${timestamp}.${input.rawBody.toString("utf8")}`)
    .digest();
  const matches = signatures.split(" ").some((entry) => {
    const [version, signature] = entry.split(",");
    if (version !== "v1" || !signature) return false;
    const given = Buffer.from(signature, "base64");
    return given.length === expected.length && timingSafeEqual(given, expected);
  });
  if (!matches) throw new InvalidWebhookError("Invalid webhook signature");
}

export const resendProvider: IntegrationProvider<ResendConfig, ResendSecret> = {
  type: "resend",
  configSchema,
  secretSchema,
  verify: async (config, secret) => {
    const response = await fetch(`${API}/domains`, {
      headers: { Authorization: `Bearer ${secret.apiKey}` },
    });
    if (response.ok) {
      const { data } = (await response.json()) as {
        data: { name: string; status: string }[];
      };
      const domain = config.fromEmail.split("@")[1]?.toLowerCase();
      if (domain === "resend.dev") return;
      const match = data.find((item) => item.name.toLowerCase() === domain);
      if (!match) {
        throw new Error(`${domain} isn't a domain in this Resend account`);
      }
      if (match.status !== "verified") {
        throw new Error(`${domain} isn't verified in Resend yet`);
      }
      return;
    }
    const error = await resendError(response);
    if (error.name === "restricted_api_key" && response.status === 401) return;
    throw new Error(
      `Resend API key didn't work: ${error.message ?? `HTTP ${response.status}`}`,
    );
  },
  prepareConfig: withWebhookToken,
  describe: (config) => ({
    webhookUrl: webhookUrl("resend", config.webhookToken),
    eventsToEnable: ["email.bounced", "email.complained"],
  }),
  send: async (config, secret, message) => {
    const fromName = message.fromName ?? config.fromName;
    const replyTo = message.replyTo ?? config.replyTo;
    const response = await fetch(`${API}/emails`, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${secret.apiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        from: fromName ? `${fromName} <${config.fromEmail}>` : config.fromEmail,
        to: message.to,
        subject: message.subject,
        html: message.html,
        text: message.text,
        ...(replyTo ? { reply_to: replyTo } : {}),
        ...(message.headers ? { headers: message.headers } : {}),
      }),
    });
    if (!response.ok) {
      const error = await resendError(response);
      throw new Error(
        `Resend send failed: ${error.message ?? `HTTP ${response.status}`}`,
      );
    }
    const { id } = (await response.json()) as { id: string };
    return { providerMessageId: id };
  },
  parseWebhook: ({ rawBody, headers, secret }) => {
    if (!secret.webhookSecret) {
      throw new InvalidWebhookError("No webhook signing secret saved");
    }
    verifyResendSignature({ rawBody, headers, secret: secret.webhookSecret });
    const event = JSON.parse(rawBody.toString("utf8")) as {
      type: string;
      created_at: string;
      data: {
        email_id?: string;
        bounce?: { type?: string; subType?: string; message?: string };
      };
    };
    const emailId = event.data.email_id;
    if (!emailId) return [];
    const occurredAt = new Date(event.created_at);
    if (event.type === "email.complained") {
      return [
        {
          providerMessageId: emailId,
          bounceType: "hard",
          reason: "Marked as spam",
          occurredAt,
        },
      ];
    }
    if (event.type !== "email.bounced") return [];
    const bounce = event.data.bounce;
    return [
      {
        providerMessageId: emailId,
        bounceType: bounce?.type === "Permanent" ? "hard" : "soft",
        reason: bounce?.message ?? bounce?.subType ?? "Bounced",
        occurredAt,
      },
    ] satisfies BounceEvent[];
  },
};
