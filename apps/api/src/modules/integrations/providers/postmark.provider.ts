import { z } from "zod";

import type { IntegrationProvider } from "./types.js";
import { InvalidWebhookError } from "../../inbound/inboundSource.js";
import { webhookUrl, withWebhookToken } from "../../inbound/webhookToken.js";

const API = "https://api.postmarkapp.com";

const configSchema = z.object({
  fromEmail: z.string().email(),
  fromName: z.string().max(255).optional(),
  replyTo: z
    .string()
    .email()
    .optional()
    .describe(
      "Where replies go, if not fromEmail - e.g. when the sending subdomain has no inbox.",
    ),
  messageStream: z
    .string()
    .min(1)
    .optional()
    .describe("Postmark message stream to send through. Defaults to outbound."),
  webhookToken: z
    .string()
    .optional()
    .describe("Generated by subscriber.dev; any value sent is ignored."),
});

const secretSchema = z.object({
  serverToken: z.string().min(1).describe("A Postmark server API token."),
});

type PostmarkConfig = z.infer<typeof configSchema>;
type PostmarkSecret = z.infer<typeof secretSchema>;

interface PostmarkResponse {
  ErrorCode?: number;
  Message?: string;
  MessageID?: string;
}

function headers(serverToken: string) {
  return {
    Accept: "application/json",
    "Content-Type": "application/json",
    "X-Postmark-Server-Token": serverToken,
  };
}

async function body(response: Response): Promise<PostmarkResponse> {
  return ((await response.json().catch(() => null)) ?? {}) as PostmarkResponse;
}

export const postmarkProvider: IntegrationProvider<
  PostmarkConfig,
  PostmarkSecret
> = {
  type: "postmark",
  configSchema,
  secretSchema,
  verify: async (_config, secret) => {
    const response = await fetch(`${API}/server`, {
      headers: headers(secret.serverToken),
    });
    if (!response.ok) {
      const error = await body(response);
      throw new Error(
        `Postmark server token didn't work: ${error.Message ?? `HTTP ${response.status}`}`,
      );
    }
  },
  prepareConfig: withWebhookToken,
  describe: (config) => ({
    webhookUrl: webhookUrl("postmark", config.webhookToken),
    eventsToEnable: ["Bounce", "SpamComplaint"],
  }),
  send: async (config, secret, message) => {
    const fromName = message.fromName ?? config.fromName;
    const replyTo = message.replyTo ?? config.replyTo;
    const response = await fetch(`${API}/email`, {
      method: "POST",
      headers: headers(secret.serverToken),
      body: JSON.stringify({
        From: fromName ? `${fromName} <${config.fromEmail}>` : config.fromEmail,
        To: message.to,
        Subject: message.subject,
        HtmlBody: message.html,
        TextBody: message.text,
        MessageStream: config.messageStream ?? "outbound",
        ...(replyTo ? { ReplyTo: replyTo } : {}),
        ...(message.headers
          ? {
              Headers: Object.entries(message.headers).map(([Name, Value]) => ({
                Name,
                Value,
              })),
            }
          : {}),
      }),
    });
    const result = await body(response);
    if (!response.ok || result.ErrorCode !== 0 || !result.MessageID) {
      throw new Error(
        `Postmark send failed: ${result.Message ?? `HTTP ${response.status}`}`,
      );
    }
    return { providerMessageId: result.MessageID };
  },
  parseWebhook: ({ rawBody }) => {
    let event: {
      RecordType?: string;
      MessageID?: string;
      Type?: string;
      Description?: string;
      Details?: string;
      Inactive?: boolean;
      BouncedAt?: string;
    };
    try {
      event = JSON.parse(rawBody.toString("utf8")) as typeof event;
    } catch {
      throw new InvalidWebhookError("Webhook body isn't JSON");
    }
    if (!event.MessageID) return [];
    const occurredAt = event.BouncedAt ? new Date(event.BouncedAt) : new Date();
    if (event.RecordType === "SpamComplaint") {
      return [
        {
          providerMessageId: event.MessageID,
          bounceType: "hard",
          reason: "Marked as spam",
          occurredAt,
        },
      ];
    }
    if (event.RecordType !== "Bounce") return [];
    return [
      {
        providerMessageId: event.MessageID,
        bounceType: event.Inactive ? "hard" : "soft",
        reason: event.Details ?? event.Description ?? event.Type ?? "Bounced",
        occurredAt,
      },
    ];
  },
};
