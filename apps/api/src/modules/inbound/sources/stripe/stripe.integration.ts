import { z } from "zod";

import type { Stripe } from "@subscriber.dev/stripe";
import {
  createStripeClientForKey,
  STRIPE_API_VERSION,
} from "@subscriber.dev/stripe";

import type { ConfigurableIntegration } from "../../../integrations/providers/types.js";
import type { StripeSecret } from "./stripe.source.js";
import { webhookUrl, withWebhookToken } from "../../webhookToken.js";
import {
  isResourceMissing,
  STRIPE_EVENTS_TO_ENABLE,
  stripeSource,
} from "./stripe.source.js";

const configSchema = z.object({
  webhookToken: z
    .string()
    .optional()
    .describe("Generated by subscriber.dev; any value sent is ignored."),
});

type StripeConfig = z.infer<typeof configSchema> & {
  webhookEndpointId?: string;
  webhookStatus?: "automatic" | "manual";
};

const secretSchema = z.object({
  apiKey: z
    .string()
    .min(1)
    .describe(
      "Restricted Stripe API key with Customers: Read, used to look up customer emails. Also give it Webhook Endpoints: Write and subscriber.dev creates the webhook endpoint in Stripe for you.",
    ),
  webhookSecret: z
    .string()
    .startsWith("whsec_")
    .optional()
    .describe(
      "Only if you add the webhook endpoint in Stripe yourself: its signing secret.",
    ),
}) satisfies z.ZodType<StripeSecret>;

type EnabledEvent = Stripe.WebhookEndpointUpdateParams.EnabledEvent;

const lacksPermission = (error: unknown) =>
  typeof error === "object" &&
  error !== null &&
  "statusCode" in error &&
  error.statusCode === 403;

async function upsertWebhookEndpoint(apiKey: string, config: StripeConfig) {
  const stripe = createStripeClientForKey(apiKey);
  const url = webhookUrl(stripeSource.source, config.webhookToken);
  const enabled_events: EnabledEvent[] = [...STRIPE_EVENTS_TO_ENABLE];

  if (config.webhookEndpointId) {
    try {
      const existing = await stripe.webhookEndpoints.retrieve(
        config.webhookEndpointId,
      );
      const events = existing.enabled_events as EnabledEvent[];
      return await stripe.webhookEndpoints.update(existing.id, {
        url,
        enabled_events: events.includes("*")
          ? ["*"]
          : [...new Set([...events, ...enabled_events])],
      });
    } catch (error) {
      if (!isResourceMissing(error)) throw error;
    }
  }

  const { data } = await stripe.webhookEndpoints.list({ limit: 100 });
  for (const stale of data.filter((endpoint) => endpoint.url === url)) {
    await stripe.webhookEndpoints.del(stale.id);
  }
  return stripe.webhookEndpoints.create({
    url,
    enabled_events,
    api_version: STRIPE_API_VERSION,
    description: "subscriber.dev workflow triggers",
  });
}

export const stripeIntegration: ConfigurableIntegration<
  StripeConfig,
  StripeSecret
> = {
  type: stripeSource.source,
  configSchema,
  secretSchema,
  verify: async (_config, secret) => {
    try {
      await createStripeClientForKey(secret.apiKey).customers.list({
        limit: 1,
      });
    } catch (error) {
      throw new Error(
        `Stripe API key can't read customers: ${error instanceof Error ? error.message : String(error)}`,
      );
    }
  },
  prepareConfig: (config, existing) => ({
    ...withWebhookToken(config, existing),
    webhookEndpointId:
      typeof existing?.webhookEndpointId === "string"
        ? existing.webhookEndpointId
        : undefined,
    webhookStatus:
      existing?.webhookStatus === "automatic" ||
      existing?.webhookStatus === "manual"
        ? existing.webhookStatus
        : undefined,
  }),
  connect: async (config, secret) => {
    if (secret.webhookSecret && !config.webhookEndpointId) {
      return { config: { ...config, webhookStatus: "manual" }, secret };
    }
    try {
      const endpoint = await upsertWebhookEndpoint(secret.apiKey, config);
      return {
        config: {
          ...config,
          webhookEndpointId: endpoint.id,
          webhookStatus: "automatic",
        },
        secret: endpoint.secret
          ? { ...secret, webhookSecret: endpoint.secret }
          : secret,
      };
    } catch (error) {
      if (lacksPermission(error)) return { config, secret };
      throw new Error(
        `Couldn't create the Stripe webhook: ${error instanceof Error ? error.message : String(error)}. Fix that and save again, or add the webhook in Stripe yourself and save its signing secret as webhookSecret.`,
      );
    }
  },
  disconnect: async (config, secret) => {
    if (!config.webhookEndpointId) return;
    await createStripeClientForKey(secret.apiKey).webhookEndpoints.del(
      config.webhookEndpointId,
    );
  },
  describe: (config) => ({
    webhookUrl: webhookUrl(stripeSource.source, config.webhookToken),
    eventsToEnable: [...stripeSource.eventsToEnable],
    ...(config.webhookStatus
      ? {}
      : {
          nextStep:
            "Stripe has no webhook for subscriber.dev yet, so no Stripe events arrive and Stripe triggers and exit conditions won't run. Save an API key that also has Webhook Endpoints: Write and subscriber.dev adds the webhook for you, or add a webhook endpoint in Stripe for webhookUrl with the eventsToEnable and save its signing secret as webhookSecret.",
        }),
  }),
};
